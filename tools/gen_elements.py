#!/usr/bin/env python3
"""Turn tools/elements.txt into source/elements.h, validating the recipe graph."""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "elements.txt")
OUT = os.path.join(HERE, "..", "source", "elements.h")


def die(msg):
    sys.exit("gen_elements: " + msg)


els, recipes, rules = [], [], {}
for ln, line in enumerate(open(SRC, encoding="utf-8"), 1):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    parts = [p.strip() for p in line.split("|")]
    if len(parts) not in (3, 4, 5):
        die(f"line {ln}: expected 3 to 5 fields")
    name, col, shape = parts[:3]
    els.append((name, int(col, 16), shape))
    if len(parts) >= 4 and parts[3]:
        for r in parts[3].split(";"):
            a, b = [x.strip() for x in r.split("+")]
            recipes.append((a, b, name, ln))
    if len(parts) == 5:
        rules[name] = (parts[4], ln)

idx = {}
for i, (n, _, _) in enumerate(els):
    if n in idx:
        die(f"duplicate element {n}")
    idx[n] = i

pairs = {}
for a, b, r, ln in recipes:
    for x in (a, b):
        if x not in idx:
            die(f"line {ln}: unknown ingredient '{x}'")
    k = tuple(sorted((idx[a], idx[b])))
    if k in pairs and idx[r] in pairs[k]:
        die(f"line {ln}: duplicate recipe {a} + {b}")
    pairs.setdefault(k, []).append(idx[r])
if max(len(v) for v in pairs.values()) > 8:
    die("a pair makes more than 8 elements")

# starters and unlock rules: (element, progress, min, [elements])
starters, unlocks = [], []
for name, (rule, ln) in rules.items():
    w = rule.split()
    if rule == "start":
        starters.append(idx[name])
    elif len(w) == 2 and w[0] == "progress":
        unlocks.append((idx[name], int(w[1]), 0, []))
    elif len(w) > 2 and w[1] == "of":
        lst = [x.strip() for x in rule.split("of", 1)[1].split(",")]
        for x in lst:
            if x not in idx:
                die(f"line {ln}: unknown element '{x}' in unlock rule")
        unlocks.append((idx[name], 0, int(w[0]), [idx[x] for x in lst]))
    else:
        die(f"line {ln}: bad unlock rule '{rule}'")
starters.sort()
unlocks.sort()
if not starters:
    die("no starting elements")

# every element must be reachable from the starters
have = set(starters)
changed = True
while changed:
    changed = False
    for (a, b), rs in pairs.items():
        if a in have and b in have:
            for r in rs:
                if r not in have:
                    have.add(r)
                    changed = True
    for e, prog, mn, lst in unlocks:
        if e not in have and (len(have) >= prog if prog else sum(x in have for x in lst) >= mn):
            have.add(e)
            changed = True
missing = [els[i][0] for i in range(len(els)) if i not in have]
if missing:
    die("unreachable: " + ", ".join(missing))

used = set()
for a, b in pairs:
    used.update((a, b))

shapes = sorted({s for _, _, s in els})
with open(OUT, "w") as f:
    f.write("/* generated by tools/gen_elements.py from tools/elements.txt - do not edit */\n")
    f.write("#ifndef ELEMENTS_H\n#define ELEMENTS_H\n\n")
    f.write("enum {\n" + "".join(f"\tSH_{s.upper()},\n" for s in shapes) + "\tSH_COUNT\n};\n\n")
    f.write(f"#define NEL {len(els)}\n#define NSTART {len(starters)}\n")
    nrec = sum(len(v) for v in pairs.values())
    f.write(f"#define NRECIPE {nrec}\n#define NUNLOCK {len(unlocks)}\n\n")
    f.write("typedef struct { const char *name; unsigned col; unsigned char shape, final; } ElemDef;\n")
    f.write("typedef struct { short a, b, r; } RecipeDef;\n")
    f.write("/* unlocked after `progress` discoveries, or after `min` of UNLOCK_ELS[first .. first+count) */\n")
    f.write("typedef struct { short el, progress, min, first, count; } UnlockDef;\n\n")
    f.write("static const ElemDef ELEMS[NEL] = {\n")
    for i, (n, c, s) in enumerate(els):
        esc = n.replace("\\", "\\\\").replace('"', '\\"')
        f.write(f'\t{{"{esc}", 0x{c:06X}, SH_{s.upper()}, {0 if i in used else 1}}},\n')
    f.write("};\n\n")
    f.write("static const short STARTERS[NSTART] = {" + ", ".join(map(str, starters)) + "};\n\n")
    f.write("static const RecipeDef RECIPES[NRECIPE] = {\n")
    for (a, b) in sorted(pairs):
        for r in pairs[(a, b)]:
            f.write(f"\t{{{a}, {b}, {r}}},\n")
    f.write("};\n\n")
    flat, defs = [], []
    for e, prog, mn, lst in unlocks:
        defs.append(f"\t{{{e}, {prog}, {mn}, {len(flat)}, {len(lst)}}},\n")
        flat += lst
    f.write("static const short UNLOCK_ELS[] = {" + ", ".join(map(str, flat or [0])) + "};\n")
    f.write("static const UnlockDef UNLOCKS[NUNLOCK] = {\n" + "".join(defs) + "};\n\n#endif\n")
print(f"gen_elements: {len(els)} elements, {nrec} recipes, {len(unlocks)} unlocks, {len(shapes)} shapes -> source/elements.h")
print("shapes:", " ".join(shapes))
